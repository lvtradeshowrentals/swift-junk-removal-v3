// node _dev/faqtest.cjs [phone|desktop]  -> FAQ filter + accordion + keyboard checks
const { createRequire } = require('module');
const req = createRequire('C:/Users/Cleo/Desktop/world2/');
const puppeteer = req('puppeteer-core');
const path = require('path'), fs = require('fs');
const size = process.argv[2] || 'desktop';
const V = size === 'phone' ? { width: 390, height: 844, deviceScaleFactor: 2, isMobile: true, hasTouch: true } : { width: 1512, height: 1000 };
const wait = (ms) => new Promise((r) => setTimeout(r, ms));
(async () => {
  const b = await puppeteer.launch({ executablePath: 'C:\\Program Files (x86)\\Google\\Chrome\\Application\\chrome.exe', headless: 'new', args: ['--hide-scrollbars'] });
  const p = await b.newPage(); await p.setViewport(V);
  await p.setRequestInterception(true);
  p.on('request', (r) => (/cloud-data|hero-gl/.test(r.url()) ? r.abort() : r.continue()));
  p.on('pageerror', (e) => console.log('PAGEERROR:', String(e.stack).split('\n').slice(0, 3).join(' | ')));
  await p.goto('file:///' + path.join(__dirname, '..', 'index.html').split(path.sep).join('/') + '?nosmooth&nointro', { waitUntil: 'load', timeout: 120000 });
  await p.evaluate(() => document.fonts.ready); await wait(600);
  await p.evaluate(() => { const el = document.querySelector('#faq'); window.scrollTo(0, el.getBoundingClientRect().top + scrollY + (innerWidth > 900 ? 0 : 280)); });
  await wait(1500);
  const state = () => p.evaluate(() => Array.from(document.querySelectorAll('.qa')).map((l) => (l.classList.contains('off') ? 'x' : l.classList.contains('on') ? 'O' : '-') + l.querySelector('.qn').textContent).join(' '));
  console.log('initial :', await state());
  const shot = async (n) => p.screenshot({ path: path.join(__dirname, 'shots', `faq_${size}_${n}.png`) });
  await p.click('.qa:nth-child(3) button'); await wait(1100);
  console.log('open #3 :', await state(), '| expanded attrs:', await p.$$eval('.qa button', (e) => e.map((x) => x.getAttribute('aria-expanded')[0]).join('')));
  await shot('open3');
  await p.click('#faqFilter [data-f=price]'); await wait(1200);
  console.log('price   :', await state(), '| count:', await p.$eval('#faqShown', (e) => e.textContent));
  await shot('price');
  await p.click('#faqFilter [data-f=take]'); await wait(1200);
  console.log('take    :', await state(), '| count:', await p.$eval('#faqShown', (e) => e.textContent), '| pressed:', await p.$$eval('#faqFilter button', (e) => e.map((x) => x.getAttribute('aria-pressed')[0]).join('')));
  await shot('take');
  await p.click('#faqFilter [data-f=all]'); await wait(1200);
  console.log('all     :', await state());
  await p.focus('.qa:nth-child(1) button'); await p.keyboard.press('ArrowDown'); await p.keyboard.press('ArrowDown');
  console.log('focus after 2x ArrowDown:', await p.evaluate(() => document.activeElement.id));
  await p.keyboard.press('Enter'); await wait(900);
  console.log('after Enter:', await state());
  await p.keyboard.press('End'); console.log('End ->', await p.evaluate(() => document.activeElement.id));
  await p.keyboard.press('Space'); await wait(900); console.log('after Space:', await state());
  await shot('end');
  await b.close();
})();
